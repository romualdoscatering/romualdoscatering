"""Move events and menus from the current Google-based ops app into the new database.

1. In Google Drive open "Romualdo's Ops Data" → File → Download → CSV.
2. python3 tools/import_ops_export.py "Romualdo's Ops Data - docs.csv" > import_events.sql
3. Run import_events.sql in the Supabase SQL editor (as the owner), AFTER the migrations and private_seed.sql.
The output contains client names and phone numbers: don't commit it to GitHub.
"""
import csv, json, sys

KIND = {'trays': 'trays', 'packs': 'packs'}
STATUS = {'draft': 'draft', 'approval': 'for_client_approval', 'approved': 'confirmed', 'cancelled': 'cancelled'}
COURSE = {'Main dish': 'Main'}
q = lambda s: 'null' if s in (None, '') else "'" + str(s).replace("'", "''") + "'"

def main(path):
    rows = list(csv.DictReader(open(path, encoding='utf-8')))
    out = ["-- Generated by tools/import_ops_export.py — contains client details, do not commit.",
           "begin;", "select set_config('request.jwt.claim.sub', (select id::text from profiles where is_admin and active order by created_at limit 1), true);"]
    n = 0
    for r in rows:
        if r.get('coll') != 'events':
            continue
        d = json.loads(r['data'])
        if d.get('status') == 'void':
            continue
        sh = d.get('sheet') or {}
        if sh.get('status') == 'cancelled':
            continue
        kind = KIND.get(sh.get('kind'), 'buffet')
        st = STATUS.get(sh.get('status'), 'draft')
        if (sh.get('date') or d.get('date') or '') < '2026-11-24' and st == 'confirmed':
            st = 'done'
        pax = sh.get('pax') or d.get('pax') or ''
        pax = int(float(pax)) if str(pax).replace('.', '', 1).isdigit() else None
        title = (sh.get('client') or d.get('client') or d.get('name') or 'Event').strip()
        extra = {k: v for k, v in sh.items() if k not in ('menu', 'id') and v not in ('', None, [], {})}
        extra['legacy_id'] = r['path']
        price = (d.get('pricing') or {}).get('custom') or ((d.get('pricing') or {}).get('perHead', 0) or 0) * (pax or 0) or d.get('contract') or None
        cid = f"c{n}"
        out.append(f"with {cid} as (insert into clients(name, contact, phone, email) values ({q(title)}, {q(sh.get('contact'))}, {q(sh.get('mobile'))}, {q(sh.get('email'))}) returning id)")
        out.append(f"insert into events(kind, title, event_type, event_date, serve_time, venue, pax, status, contract_price, sheet, client_id) "
                   f"select '{kind}', {q(title)}, {q(sh.get('type'))}, {q(sh.get('date') or d.get('date'))}, {q(sh.get('serve') or None)}, {q(sh.get('venue'))}, "
                   f"{pax if pax is not None else 'null'}, '{st}', {price or 'null'}, {q(json.dumps(extra))}::jsonb, id from {cid};")
        for m in sh.get('menu', []):
            dish = (m.get('dish') or '').strip()
            if not dish:
                continue
            qty = m.get('qty') if kind != 'buffet' else None
            qty = qty if str(qty or '').replace('.', '', 1).isdigit() else None
            out.append(f"select add_menu_text((select id from events where sheet->>'legacy_id' = {q(r['path'])}), "
                       f"{q(COURSE.get(m.get('course'), m.get('course') or ''))}, {q(dish)}, {qty or 'null'});")
        n += 1
    out += ["select refresh_dish_stats();", "commit;"]
    print('\n'.join(out))
    print(f"-- {n} events", file=sys.stderr)

if __name__ == '__main__':
    main(sys.argv[1])
